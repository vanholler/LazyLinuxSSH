    public static AppLanguage CurrentLanguage { get; private set; } = AppLanguage.Russian;

    public static string T(string russian) =>
        CurrentLanguage == AppLanguage.English && English.TryGetValue(russian, out var english)
            ? english
            : russian;

    public static string T(string russian, params object?[] args) =>
        string.Format(CultureInfo.CurrentCulture, T(russian), args);

    public static void SetLanguage(AppLanguage language)
    {
        CurrentLanguage = language;
        ApplyResources();
    }

    public static void ApplyResources()
    {
        if (Application.Current is null) return;
        foreach (var key in English.Keys)
            Application.Current.Resources[key] = T(key);
    }
